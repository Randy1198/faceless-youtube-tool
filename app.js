// Main generator execution
document.getElementById('generateBtn').addEventListener('click', function() {
    const btn = this;
    const loader = document.getElementById('toolLoader');
    const results = document.getElementById('resultsContainer');

    btn.disabled = true;
    results.classList.add('hidden');
    loader.classList.remove('hidden');

    setTimeout(() => {
        const niche = document.getElementById('nicheSelect').value;
        const length = document.getElementById('lengthSelect').value;
        const data = automatedDatabase[niche][length];

        // Populate titles
        const ideasOutput = document.getElementById('ideasOutput');
        ideasOutput.innerHTML = '';
        data.ideas.forEach(idea => {
            const item = document.createElement('div');
            item.className = "bg-slate-900 border border-slate-700/50 p-3 rounded-lg text-sm text-slate-200 font-medium hover:border-indigo-500/50 transition";
            item.innerText = idea;
            ideasOutput.appendChild(item);
        });

        // Populate script
        const scriptBox = document.getElementById('scriptOutput');
        scriptBox.innerText = data.script;

        // Word count & estimated speaking time (Standard pace: 150 words per minute)
        const wordCount = data.script.split(/\s+/).filter(w => w.length > 0).length;
        document.getElementById('wordcountOutput').innerText = wordCount + " words";
        
        const totalSeconds = Math.round((wordCount / 150) * 60);
        document.getElementById('durationOutput').innerText = totalSeconds + "s";

        // Reset UI state
        loader.classList.add('hidden');
        results.classList.remove('hidden');
        btn.disabled = false;

        results.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }, 800);
});

// Copy script to clipboard with clean toast feedback + viral watermark
window.copyScript = function() {
    const rawText = document.getElementById('scriptOutput').innerText;
    
    // Automatically appends your domain at the bottom of copied text
    const textWithWatermark = rawText + "\n\n---\n⚡ Script generated for free at FacelessYouTubeTool.com";

    navigator.clipboard.writeText(textWithWatermark).then(() => {
        const toast = document.getElementById('toast');
        toast.classList.remove('hidden');
        setTimeout(() => {
            toast.classList.add('hidden');
        }, 2500);
    }).catch(err => {
        console.error("Copy failed: ", err);
    });
};
